// tools/WofCompact.h
// ─────────────────────────────────────────────────────────────────────────────
// Прозрачное сжатие файлов Windows (WOF, `compact /exe:lzx`) — то же, что делает
// CompactGUI. Файлы сжимаются на месте: игра запускается как обычно, Windows
// разжимает данные при чтении. Временного места не требует (файлы по одному).
// Файл, который игра перезаписывает (сохранения, настройки), становится
// обычным — это нормально.
// ─────────────────────────────────────────────────────────────────────────────
#pragma once

#include <QString>
#include <QStringList>

class QFileInfo;

namespace WofCompact {

/// Путь к compact.exe (System32). Для тестов — переменная MS_COMPACT_EXE.
QString program();
bool    isAvailable();

/// Аргументы: compress=true — сжать LZX, false — вернуть обычный вид.
/// Запускать с рабочей папкой = сжимаемая папка (обрабатывается со всеми
/// подпапками, включая скрытые файлы; ошибки отдельных файлов пропускаются).
QStringList arguments(bool compress);

/// Строка вывода compact про один обработанный файл («a.exe 100 : 50 = 2,0 к 1 [OK]»).
/// Вывод локализован, поэтому признак — числа через «:» и «=», а не слова.
bool isFileLine(const QString &line);

/// Сколько файл занимает на диске (для сжатых — меньше размера). Вне Windows — размер.
qint64 sizeOnDisk(const QFileInfo &fi);

} // namespace WofCompact
